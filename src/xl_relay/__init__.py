"""xl-relay — сервер переезда профилей XLauncher между компьютерами пользователя.

Работает на машине пользователя внутри его Tailscale-сети и хранит только шифротекст:
ключ шифрования есть лишь у лаунчеров (в ключе переезда), серверу он не нужен и не передаётся.

Два вида данных:
- пакеты переезда (`store/packages/<package_id>/`): фрагменты шифротекста по ~8 МиБ, meta.json с хешами;
  удаляются только по confirm/cancel с токеном удаления (сервер хранит лишь его sha256) или вручную;
- связка машин (`store/groups/<group_id>/`): heartbeat'ы машин и почтовые ящики для режима «Забрать сюда».
  group_id выводится из кода связки на клиентах; сообщения подписывают и проверяют сами лаунчеры,
  сервер их не читает.

Настройки — переменные окружения (файл relay.env на сервере, в репозитории его нет):
  XL_RELAY_BIND        адрес, который слушать (Tailscale-адрес машины; не 0.0.0.0)
  XL_RELAY_PORT        порт, по умолчанию 47120
  XL_RELAY_STORE       папка данных
  XL_RELAY_MIN_FREE_GB сколько места оставлять свободным, по умолчанию 5
"""

